batch_dir = Path("geckowo_batches")
doodle_posts = []

for batch_file in batch_dir.glob("batch_*.json"):
    if "doodles" in batch_file.name:
        continue
    try:
        with open(batch_file, 'r', encoding='utf-8') as f:
            data = json.load(f)
            if not isinstance(data, list):
                continue
            for post in data:
                sid = post.get('link', '').split('/')[-1]
                if not sid:
                    sid = post.get('status_id', '')
                if sid in DOODLE_IDS:
                    imgs = post.get('imgs', [])
                    if imgs:
                        doodle_posts.append({
                            "link": post.get('link', f"https://x.com/geckowo/status/{sid}"),
                            "imgs": imgs
                        })
                        print(f"Found {sid} in {batch_file.name}")
    except Exception as e:
        print(f"Error reading {batch_file.name}: {e}")

print(f"\nTotal doodles with images: {len(doodle_posts)}")

# Update the doodles batch file
output_file = Path("geckowo_batches/batch_doodles_2026-01-11.json")
